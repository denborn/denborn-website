test('a game master’s screens break no rule a machine can check: campaigns, each rule, encounters', async ({ page }) => {
  await page.goto('/campaigns')
  await expectAccessible(page, 'campaigns, none yet')
  await setCampaign(page, 'Dawn Patrol')
  await expectAccessible(page, 'campaign, saved')
  for (const rule of [/^Name/, /^Pokémon/, /^Starting level/, /^Starting Pokédollars/, /^Natures/, /^Moves/, /^Common moves/, /^Item packs/]) {
    await page.getByRole('button', { name: rule }).first().click()
    await expectAccessible(page, `rule ${String(rule)}`)
    await page.getByRole('button', { name: 'DONE' }).click()
  }
  await page.getByRole('button', { name: 'ENCOUNTERS' }).click()
  await expectAccessible(page, 'encounters, none yet')
  await page.getByRole('button', { name: 'NEW', exact: true }).click()
  await draftEncounter(page, 'The quarry')
  await expectAccessible(page, 'encounter: an enemy')
  await page.getByRole('button', { name: 'DONE' }).click()
  await expectAccessible(page, 'encounter')
})

test('a session’s and a fight’s screens break no rule a machine can check, on the game master’s side and on a player’s', async ({ page: gm }) => {
  const { player, code: join } = await table(gm)
  await gm.getByRole('button', { name: 'NEW ENCOUNTER' }).click()
  await draftEncounter(gm, 'The quarry')
  await gm.getByRole('button', { name: 'DONE' }).click()
  await gm.getByRole('button', { name: 'SAVE THE ENCOUNTER' }).click()
  await gm.getByRole('button', { name: 'BACK' }).click()

  await player.goto('/session')
  await expectAccessible(player, 'join: the code')
  await ask(player, join)
  await expectAccessible(player, 'join: waiting')
  await expectAccessible(gm, 'host: a request')
  await gm.getByRole('group', { name: 'Volt' }).getByRole('button', { name: 'LET IN' }).click()
  await expect(player.getByText('Volt (you)')).toBeVisible()
  await expectAccessible(player, 'join: in the session')
  await gm.getByRole('button', { name: /^Volt/ }).click()
  await expectAccessible(gm, 'host: a member opened')

  // Between two fights: the game master's give-or-take and rest, the player's four views.
  await gm.getByRole('button', { name: 'GIVE OR TAKE' }).click()
  await expectAccessible(gm, 'give or take')
  await gm.getByRole('button', { name: 'BACK' }).click()
  await gm.getByRole('button', { name: /^Volt/ }).click()
  await gm.getByRole('button', { name: 'REST', exact: true }).click()
  const yours = player.getByRole('group', { name: 'Your character' })
  for (const [row, where] of [[/^PLACE POINTS/, 'points'], [/^EVOLVE/, 'evolve'], [/^BAG/, 'bag'], [/^POKÉMON CENTER/, 'rest']] as const) {
    await yours.getByRole('button', { name: row }).click()
    await expectAccessible(player, `progress: ${where}`)
    await player.getByRole('button', { name: 'BACK' }).click()
  }

  // The fight: the game master's seat and the player's, while choosing and once a round was played.
  await gm.getByRole('button', { name: /^The quarry/ }).click()
  await gm.getByRole('button', { name: 'LAUNCH' }).click()
  await expect(gm.getByRole('button', { name: 'FIGHT' })).toBeVisible({ timeout: 30_000 })
  await expect(player.getByRole('button', { name: 'FIGHT' })).toBeVisible()
  await expectAccessible(gm, 'game master: the commands')
  await openTools(gm, 'The quarry · Round 1')
  await expectAccessible(gm, 'game master: tools')
  await gm.getByRole('button', { name: 'BACK' }).click()
  await expectAccessible(player, 'fight: the commands')
  await player.getByRole('button', { name: 'BAG' }).click()
  await expectAccessible(player, 'fight: the Bag')
  await player.getByRole('button', { name: 'BACK' }).click()
  await player.getByRole('button', { name: 'FIGHT' }).click()
  await expectAccessible(player, 'fight: the moves')
  await player.getByRole('button', { name: /Thunder Shock/ }).click()
  await expectAccessible(player, 'fight: the target')
  await player.getByRole('group', { name: 'FOES' }).getByRole('button').first().click()
  await expectAccessible(player, 'fight: locked')
  await gm.getByRole('button', { name: 'FIGHT' }).click()
  await expectAccessible(gm, 'game master: an enemy’s moves')
  await gm.getByRole('button', { name: /^Thunder Shock/ }).click()
  await expectAccessible(gm, 'game master: the target')
  await gm.getByRole('group', { name: 'PARTY' }).getByRole('button').first().click()
  await expect(gm.getByRole('button', { name: 'SKIP' })).toBeVisible()
  await expectAccessible(gm, 'game master: a round being told')
  await expectAccessible(player, 'fight: a round being told')
  await gm.getByRole('button', { name: 'SKIP' }).click()
  await openTools(gm, 'The quarry · Round 2')
  await expectAccessible(gm, 'game master: tools after a round')
  await gm.getByRole('button', { name: 'END THE ENCOUNTER' }).click()
  await expectAccessible(gm, 'rewards')
})
