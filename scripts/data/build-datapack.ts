/**
 * Builds the game data pack and writes it to src/data/generated/pack.json.
 *
 *   node scripts/data/build-datapack.ts            build; stop if anything is missing or if the pack is not the accepted one
 *   node scripts/data/build-datapack.ts --accept   build and record this pack as the accepted one
 *   node scripts/data/build-datapack.ts --report   also write data-sources/reports/data-pack.md for the owner
 *
 * The accepted pack's fingerprint is committed (data-sources/pack-fingerprint.json).
 * A build whose pack differs from it stops and lists what changed: a new
 * engine or PokéAPI version never rewrites the game data silently.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { join } from 'node:path'
import { buildDataPack } from './lib/build.ts'
import { crossCheck } from './lib/cross-check.ts'
import { type Fingerprint, SECTIONS, changes, fingerprintOf } from './lib/fingerprint.ts'
import { ROOT, readJson, stableJson, writeJson } from './lib/pinned.ts'

const FINGERPRINT = join(ROOT, 'data-sources/pack-fingerprint.json')
const OUT = join(ROOT, 'src/data/generated/pack.json')
const REPORT = join(ROOT, 'data-sources/reports/data-pack.md')

const accept = process.argv.includes('--accept')
const report = process.argv.includes('--report')

const { pack, problems, notes, lock } = await buildDataPack()
if (problems.length) {
  console.error(`The data pack cannot be built. ${problems.length} problem(s):`)
  for (const problem of problems) console.error(`  - ${problem}`)
  process.exit(1)
}

const fingerprint = fingerprintOf(pack)
const accepted = existsSync(FINGERPRINT) ? await readJson<Fingerprint>(FINGERPRINT) : null
const changed = accepted ? changes(accepted, fingerprint) : []
if (accept) {
  if (accepted && changed.length) {
    console.log(`Changes since the accepted pack (${accepted.version}):`)
    for (const line of changed) console.log(`  ${line}`)
  }
  await writeJson(FINGERPRINT, fingerprint)
} else if (!accepted || accepted.version !== pack.version) {
  console.error(
    accepted
      ? `The data pack (${pack.version}) is not the accepted one (${accepted.version}). ${changed.length} entr${changed.length === 1 ? 'y' : 'ies'} changed:`
      : 'No data pack has been accepted yet.',
  )
  for (const line of changed.slice(0, 200)) console.error(`  ${line}`)
  console.error('Review the changes, then run: pnpm data:accept')
  process.exit(1)
}

await mkdir(join(ROOT, 'src/data/generated'), { recursive: true })
await writeFile(OUT, stableJson(pack, 0))

const count = (section: (typeof SECTIONS)[number]) => Object.keys(pack[section]).length
console.log(
  `Data pack ${pack.version}: ${count('species')} species, ${count('moves')} moves, ${count('abilities')} Abilities, ${count('items')} items`,
)

if (report) {
  const differences = await crossCheck(pack, lock)
  const bag = Object.values(pack.items).filter((item) => item.bag)
  const lines = [
    '# Data pack report',
    '',
    `Pack \`${pack.version}\`, from @pkmn/dex ${pack.sources.engine} and PokéAPI \`${pack.sources.pokeapi.slice(0, 7)}\`.`,
    'Generated by `pnpm data:report`. Nothing here is a ruling: it is what the sources say, for the owner to rule on.',
    '',
    `## Showdown and PokéAPI disagree (${differences.length})`,
    '',
    'The battle runs on Showdown\'s value.',
    '',
    ...(differences.length ? differences.map((line) => `- ${line}`) : ['None.']),
    '',
    `## Descriptions that fall back to English (${notes.length})`,
    '',
    ...(notes.length ? notes.map((line) => `- ${line}`) : ['None.']),
    '',
    `## Bag items (${bag.length})`,
    '',
    '| Item | Effect in Denborn |',
    '|---|---|',
    ...bag
      .sort((a, b) => (a.id < b.id ? -1 : 1))
      .map((item) => `| ${item.name.en} | \`${JSON.stringify(item.bag)}\` |`),
    '',
  ]
  await mkdir(join(ROOT, 'data-sources/reports'), { recursive: true })
  await writeFile(REPORT, lines.join('\n'))
  console.log(`Report written: ${differences.length} disagreement(s), ${notes.length} note(s)`)
}
